package com.ledgerflow.entity;

import jakarta.persistence.*;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.Size;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

/**
 * Represents a financial transaction — a single money movement event.
 *
 * A Transaction is the "header" record for any fund movement.
 * Every Transaction will have exactly 2 LedgerEntry rows:
 *   - One DEBIT entry  (money leaving an account)
 *   - One CREDIT entry (money arriving at an account)
 *
 * This is the core of double-entry bookkeeping.
 * The sum of all LedgerEntry amounts for a Transaction must equal zero
 * (debits are positive, credits are negative, or vice versa by convention).
 *
 * We use the convention:
 *   DEBIT  = positive amount (money leaves the source account)
 *   CREDIT = positive amount (money arrives at the destination account)
 *   Both entries share the same amount value.
 *
 * Table: transactions
 */
@Entity
@Table(name = "transactions", indexes = {
        @Index(name = "idx_transactions_reference", columnList = "reference_number"),
        @Index(name = "idx_transactions_status", columnList = "status"),
        @Index(name = "idx_transactions_created_at", columnList = "created_at")
})
@Getter
@Setter
@NoArgsConstructor
public class Transaction {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * A unique human-readable reference number (e.g., "TXN-20260828-000001").
     * Used for customer-facing communication and audit lookups.
     */
    @Size(max = 50)
    @Column(name = "reference_number", unique = true, length = 50)
    private String referenceNumber;

    /**
     * The type of this transaction.
     */
    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(name = "transaction_type", nullable = false, length = 30)
    private TransactionType transactionType;

    /**
     * The monetary amount being transferred.
     * ALWAYS BigDecimal. NEVER double or float.
     */
    @NotNull
    @PositiveOrZero
    @Column(nullable = false, precision = 19, scale = 4)
    private BigDecimal amount;

    /**
     * Currency code (ISO 4217). Defaults to INR for this project.
     */
    @Column(length = 3, nullable = false)
    private String currency = "INR";

    /**
     * Current status of this transaction.
     */
    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private TransactionStatus status = TransactionStatus.PENDING;

    /**
     * Optional human-readable description/note.
     */
    @Size(max = 255)
    @Column(length = 255)
    private String description;

    /**
     * If this transaction was created as part of an ACH batch,
     * this field will reference the batch ID (set in Phase 8+).
     * Nullable — not all transactions belong to a batch.
     */
    @Column(name = "ach_batch_id")
    private Long achBatchId;

    /**
     * The ledger entries (debits and credits) generated by this transaction.
     * Every committed transaction has exactly 2 entries.
     */
    @OneToMany(mappedBy = "transaction", cascade = CascadeType.ALL, fetch = FetchType.LAZY)
    private List<LedgerEntry> ledgerEntries = new ArrayList<>();

    /**
     * Timestamp when this transaction record was created.
     */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    /**
     * When the transaction was completed (SETTLED or FAILED).
     * Null while still PENDING or PROCESSING.
     */
    @Column(name = "completed_at")
    private Instant completedAt;

    // ---------- Enums ----------

    /**
     * What kind of money movement this transaction represents.
     */
    public enum TransactionType {
        TRANSFER,        // Fund transfer between two accounts
        DEPOSIT,         // Money added to an account (from external source)
        WITHDRAWAL,      // Money removed from an account (to external destination)
        ACH_CREDIT,      // Incoming ACH payment
        ACH_DEBIT,       // Outgoing ACH payment
        REVERSAL         // Compensating/reversal transaction (saga rollback)
    }

    /**
     * Lifecycle status of the transaction.
     *
     * Flow for a normal transfer:
     *   PENDING → PROCESSING → COMPLETED
     *
     * Flow for a failed transfer:
     *   PENDING → PROCESSING → FAILED → (saga) → REVERSED
     */
    public enum TransactionStatus {
        PENDING,     // Created but not yet processed
        PROCESSING,  // Currently being executed
        COMPLETED,   // Successfully settled
        FAILED,      // Failed — ledger entries have NOT been posted
        REVERSED     // Failed and reversed via compensating transaction
    }
}
